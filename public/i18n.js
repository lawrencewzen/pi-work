let currentLocale = localStorage.getItem('piwork_lang') || 'zh';
if (!translations[currentLocale]) currentLocale = 'zh';

export function getLocale() {
  return currentLocale;
}

export function setLocale(lang) {
  if (translations[lang]) {
    currentLocale = lang;
    localStorage.setItem('piwork_lang', lang);
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  }
}

export function t(key, vars = {}) {
  const dict = translations[currentLocale] || translations.zh;
  let text = dict[key] || translations.zh[key] || key;
  for (const [k, v] of Object.entries(vars)) {
    text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}

export function tPlural(key, n, vars = {}) {
  const count = Number(n) || 0;
  if (count === 1) {
    const dict = translations[currentLocale] || translations.zh;
    if (dict[`${key}_one`]) return t(`${key}_one`, { n: count, ...vars });
  }
  return t(key, { n: count, ...vars });
}

export function applyI18n(root = document) {
  if (!root || !root.querySelectorAll) return;
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (!key) return;
    el.textContent = t(key);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (!key) return;
    el.setAttribute('placeholder', t(key));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.getAttribute('data-i18n-title');
    if (!key) return;
    el.setAttribute('title', t(key));
  });
}

if (typeof window !== 'undefined') {
  window.t = t;
  window.tPlural = tPlural;
  window.getLocale = getLocale;
  window.setLocale = setLocale;
  window.applyI18n = applyI18n;
}
